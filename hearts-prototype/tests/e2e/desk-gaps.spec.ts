import { expect, test } from '@playwright/test'

async function signIn(page: import('@playwright/test').Page, email: string, password: string, next: string) {
  await page.goto(`/login?next=${encodeURIComponent(next)}`)
  await page.getByTestId('login-email').fill(email)
  await page.getByTestId('login-password').fill(password)
  await page.getByTestId('login-submit').click()
  await page.waitForURL((url) => !url.pathname.startsWith('/login'))
}

test('a learner can open Gather from Home and Lanes, and the bottom bar stays as it is', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await signIn(page, 'elm-learner@hearts.test', 'portal-learner', '/p/east-london')
  await expect(page.getByTestId('home')).toBeVisible()
  await expect(page.getByTestId('tab-gather')).toHaveCount(0)
  await expect(page.getByTestId('home-gather-all')).toBeVisible()
  await page.getByTestId('home-gather-all').click()
  await expect(page.getByTestId('gather')).toBeVisible()
  await page.goto('/p/east-london/lanes')
  await expect(page.getByTestId('open-gather')).toBeVisible()
  await page.getByTestId('open-gather').click()
  await expect(page).toHaveURL(/\/gather$/)
  await expect(page.getByTestId('gather')).toBeVisible()
})

test('the learner live page opens, and Live recordings links to it', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await signIn(page, 'elm-learner@hearts.test', 'portal-learner', '/p/east-london')
  await expect(page.getByTestId('open-live')).toHaveText('Live recordings')
  await page.getByTestId('open-live').click()
  await expect(page).toHaveURL(/\/p\/east-london\/live$/)
  await expect(page.getByTestId('live-home')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Live recordings' })).toBeVisible()
  await page.goto('/p/east-london/live')
  await expect(page.getByTestId('live-home')).toBeVisible()

  await page.setViewportSize({ width: 1280, height: 900 })
  await signIn(page, 'elm-teacher@hearts.test', 'portal-teacher', '/p/east-london/admin/live')
  await expect(page.getByTestId('desk-live')).toBeVisible()
  await expect(page.locator('h1').first()).toContainText('Live recordings')
  await expect(page.getByTestId('desk-open-live')).toHaveAttribute('href', '/p/east-london/live')
  await page.getByTestId('desk-open-live').click()
  await expect(page.getByTestId('live-home')).toBeVisible()
})

test('publishing a new course asks to put it on a code or give it to people who joined', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await signIn(page, 'elm-admin@hearts.test', 'portal-admin', '/p/east-london/admin/access')
  await expect(page.getByTestId('admin-access')).toBeVisible()
  await page.getByTestId('portal-pack-title').fill('Audit set')
  await page.getByTestId('portal-pack-submit').click()
  await expect(page.getByTestId('notice')).toBeVisible()
  await page.getByTestId('new-code-role').selectOption('learner')
  await page.getByTestId('new-code-pack').selectOption({ label: 'Audit set' })
  await page.getByTestId('new-code-teacher').selectOption({ index: 1 })
  await page.getByTestId('new-code-submit').click()
  await expect(page.getByTestId('notice')).toBeVisible()

  await page.goto('/p/east-london/admin/content')
  await expect(page.getByTestId('admin-content')).toBeVisible()
  await page.getByTestId('local-course-title').fill('Audit night')
  await page.getByTestId('local-course-submit').click()
  await expect(page.getByTestId('notice')).toBeVisible()
  await page.getByRole('link', { name: 'Audit night' }).first().click()
  await expect(page.getByTestId('course-on-codes')).toBeVisible()
  await expect(page.getByTestId('course-on-codes')).toContainText('Learners cannot open this yet')
  const offer = page.getByTestId('offer-code')
  const labels = await offer.locator('option').allTextContents()
  const match = labels.find((label) => label.includes('Audit set'))
  expect(match, labels.join(' | ')).toBeTruthy()
  await offer.selectOption({ label: match! })
  await page.getByTestId('offer-on-code').click()
  await expect(page.getByTestId('notice')).toContainText('Audit night is on')
  await expect(page.getByTestId('course-on-codes')).toHaveCount(0)
})

test('the master Gather item opens Circle answers under that name', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await signIn(page, 'master@hearts.test', 'hearts-master', '/master')
  const item = page.getByTestId('nav-circle')
  await expect(item).toContainText('Circle answers')
  await expect(item).not.toContainText('Gather')
  await expect(item).toHaveAttribute('href', '/master/circle')
  await item.click()
  await expect(page.getByTestId('master-circle')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Circle answers' })).toBeVisible()
})
