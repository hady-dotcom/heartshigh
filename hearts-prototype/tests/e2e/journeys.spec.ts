    await page.getByTestId('learner-welcome').fill('https://www.youtube.com/watch?v=MK5q_zMiX1g')
    await page.getByTestId('learner-intro').fill('https://www.youtube.com/watch?v=ECaTWkof57E')
    await page.getByTestId('teacher-welcome').fill('https://www.youtube.com/watch?v=ECaTWkof57E')
    await page.getByTestId('teacher-intro').fill('https://www.youtube.com/watch?v=MK5q_zMiX1g')
    await page.getByTestId('save-settings').click()
