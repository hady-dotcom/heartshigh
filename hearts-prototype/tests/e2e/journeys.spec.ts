    await expect(page.getByTestId('youtube-url')).toHaveCount(0)
    await page.getByTestId('point-prompt').fill('A question only for one learner')
    await page.getByTestId('point-audience').selectOption('self')
    await page.getByTestId('point-submit').click()
    await expect(page.getByTestId('notice')).toContainText('Question placed')
