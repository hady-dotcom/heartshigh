    await expect(page.getByTestId('notice')).toContainText('Question placed')
    await expect(async () => {
      await page.getByTestId('preview-play').click()
      await expect(page.getByTestId('preview-readout')).not.toHaveText('0:00', { timeout: 1500 })
    }).toPass({ timeout: 15000 })
    await page.getByTestId('preview-pause').click()
    await page.getByTestId('point-timestamp').fill('6')
    await page.getByTestId('point-prompt').fill('What changed after two weeks?')
    await page.getByTestId('point-timing').selectOption('future')
    await page.getByTestId('point-delay').fill('2')
    await page.getByTestId('point-contingent').selectOption({ index: 1 })
    await page.getByTestId('point-submit').click()
