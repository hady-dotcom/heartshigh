import { expect, test, type Page } from '@playwright/test'
import { artifactDir } from './artifact-dir'

const DESK = { width: 1280, height: 800 }
const PHONE = { width: 390, height: 844 }
const SHOTS = artifactDir('screenshots')

async function signIn(page: Page, email: string, password: string, next: string) {
  await page.goto(`/login?next=${encodeURIComponent(next)}`)
  await page.getByTestId('login-email').fill(email)
  await page.getByTestId('login-password').fill(password)
  await page.getByTestId('login-submit').click()
  await page.waitForURL((url) => !url.pathname.startsWith('/login'))
}

function watch(page: Page) {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('response', (response) => {
    const url = response.url()
    if (response.status() >= 500 && !url.includes('favicon')) errors.push(`${response.status()} ${url}`)
  })
  return errors
}

async function quiet(page: Page) {
  await expect(page.getByText('Application error')).toHaveCount(0)
  await expect(page.getByText('This page could not')).toHaveCount(0)
}

async function releaseKillSwitch(page: Page) {
  if (await page.getByTestId('experiments-killed').isVisible().catch(() => false)) {
    await page.getByTestId('kill-switch').getByRole('button').click()
    await expect(page.getByTestId('experiments-killed')).toHaveCount(0)
  }
}

