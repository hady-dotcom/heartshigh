import { expect, test } from '@playwright/test'

async function signIn(page: import('@playwright/test').Page, email: string, password: string, next: string) {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`/login?next=${encodeURIComponent(next)}`)
  await page.getByTestId('login-email').fill(email)
  await page.getByTestId('login-password').fill(password)
  await page.getByTestId('login-submit').click()
  await page.waitForURL((url) => !url.pathname.startsWith('/login'))
}

test('Codes, Teach and the quick links fit a phone and show WhatsApp and QR', async ({ page }) => {
  await signIn(page, 'elm-admin@hearts.test', 'portal-admin', '/p/east-london/admin/access')
  await expect(page.getByTestId('desk-narrow')).toBeHidden()
  await expect(page.getByTestId('admin-access')).toBeVisible()
  const quick = page.getByTestId('quick-teacher')
  await expect(quick).toBeVisible()
  const box = await quick.boundingBox()
  expect(box).toBeTruthy()
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  await quick.click()
  const fresh = page.getByTestId('fresh-code')
  await expect(fresh).toBeVisible()
  await expect(fresh.getByTestId('share-whatsapp')).toBeVisible()
  await expect(fresh.getByTestId('fresh-qr')).toBeVisible()
  await page.getByTestId('quick-learner').click()
  await expect(fresh).toBeVisible()
  await page.getByTestId('quick-admin').click()
  await expect(fresh).toBeVisible()
  await expect(fresh.getByTestId('share-whatsapp')).toBeVisible()
  await expect(fresh.getByTestId('fresh-qr')).toBeVisible()

  await page.goto('/p/east-london/admin/teach')
  await expect(page.getByTestId('desk-narrow')).toBeHidden()
  await expect(page.getByTestId('admin-teach')).toBeVisible()
  const give = page.getByTestId('grant-course')
  await expect(give).toBeVisible()
  const giveBox = await give.boundingBox()
  expect(giveBox).toBeTruthy()
  expect(giveBox!.x + giveBox!.width).toBeLessThanOrEqual(390)
  await give.click()
  await give.click()
  await give.click()
  await expect(page.getByTestId('admin-teach')).toBeVisible()

  await page.goto('/p/east-london/admin/bring-in')
  await expect(page.getByTestId('desk-narrow')).toBeHidden()
  const bring = page.getByTestId('bring-in-publish-ready').first()
  await expect(bring).toBeVisible()
  const bringBox = await bring.boundingBox()
  expect(bringBox).toBeTruthy()
  expect(bringBox!.x + bringBox!.width).toBeLessThanOrEqual(390)
})
