import { expect, test, type Browser, type Page } from '@playwright/test'
import { mkdirSync } from 'node:fs'

const SHOTS = '/opt/cursor/artifacts/screenshots'
const NOTE = 'We watch the films after dinner'

async function shot(page: Page, name: string) {
  mkdirSync(SHOTS, { recursive: true })
  await page.addStyleTag({ content: 'nextjs-portal, [data-nextjs-toast], [data-next-badge-root] { display: none !important; }' }).catch(() => undefined)
  await page.waitForTimeout(250)
  await page.screenshot({ path: `${SHOTS}/${name}.png`, caret: 'initial' })
}

async function signIn(page: Page, email: string, password: string, next: string) {
  await page.goto(`/login?next=${encodeURIComponent(next)}`)
  await page.getByTestId('login-email').fill(email)
  await page.getByTestId('login-password').fill(password)
  await page.getByTestId('login-submit').click()
  await page.waitForURL((url) => !url.pathname.startsWith('/login'))
}

async function parentContext(browser: Browser) {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
  await context.grantPermissions(['clipboard-read', 'clipboard-write']).catch(() => undefined)
  return context
}

test('a signed-out parent uses the course player and keeps the answer on the phone', async ({ browser }) => {
  const context = await parentContext(browser)
  const page = await context.newPage()
  await page.goto('/p/parenting/courses')
  await expect(page.getByTestId('course-home')).toBeVisible()
  await expect(page.getByTestId('library-collection').filter({ hasText: 'Guiding Home Learning' })).toBeVisible()
  await shot(page, 'parent-01-courses')
  await page.getByTestId('course-card').filter({ hasText: 'Welcome' }).first().click()
  await expect(page.getByTestId('course-overview')).toBeVisible()
  await expect(page.getByTestId('sequence-module').first()).toBeVisible()
  await expect(page.getByTestId('buffet-talk').first()).toBeVisible()
  await expect(page.getByTestId('start-part')).toContainText(/Start film \d+/)
  await shot(page, 'parent-02-sections')
  await page.getByTestId('start-part').click()
  await expect(page.getByTestId('course')).toBeVisible()
  await expect(page.getByTestId('vimeo-player')).toBeVisible()
  await expect(page.getByTestId('question-strip')).toBeVisible()
  await expect(page.getByTestId('sequence-question')).toBeVisible()
  await expect(page.getByTestId('garden-next')).toBeVisible()
  await expect(page.getByTestId('back')).toHaveAttribute('href', /\/course\/\d+$/)
  await expect(page.getByTestId('sequence-back')).toHaveAttribute('href', /\/course\/\d+$/)
  await expect(page.getByTestId('film-share-link')).toHaveAttribute('data-url', /\/course\/\d+\?part=\d+/)
  await expect(page.getByTestId('sequence-progress-line')).toBeVisible()
  await shot(page, 'parent-03-film')
  await page.getByTestId('film-share-link').click()
  await expect(page.getByTestId('film-share-link')).toHaveText(/Copied|Share link/)
  await shot(page, 'parent-04-share-link')
  await page.getByTestId('answer-point').click()
  await expect(page.getByTestId('popup-prompt')).toBeVisible()
  await page.getByTestId('answer-text').fill(NOTE)
  await page.getByTestId('answer-private').uncheck()
  await page.getByTestId('answer-share').check()
  await page.getByTestId('answer-share-learners').check()
  await shot(page, 'parent-05-answer')
  await page.getByTestId('answer-submit').click()
  await expect(page.getByTestId('keep-sheet')).toBeVisible()
  await expect(page.getByTestId('sheet-copy')).toContainText('already on this phone')
  await shot(page, 'parent-06-share-teacher-offer')
  await page.getByTestId('not-now').click()
  await expect(page.getByTestId('keep-sheet')).toHaveCount(0)
  const kept = await page.evaluate(() => JSON.parse(window.localStorage.getItem('hearts.guest.v1') || '{}') as { answers?: { body?: string; shareWithTeacher?: boolean }[]; progress?: { lessonId?: number }[] })
  expect(kept.answers?.[0]?.body).toBe(NOTE)
  expect(kept.answers?.[0]?.shareWithTeacher).toBe(true)
  expect(kept.progress?.length).toBeGreaterThan(0)
  await page.getByTestId('garden-next').click()
  await expect(page.getByTestId('garden-prev')).toBeVisible()
  await expect(page.getByTestId('film-prev')).toBeVisible()
  await expect(page.getByTestId('back')).toHaveAttribute('href', /\/course\/\d+$/)
  await page.getByTestId('sequence-back').click()
  await expect(page.getByTestId('start-part')).toContainText(/Continue film/)
  await context.close()
})

test('Hannah Price sees an answer a parent shared with their teacher', async ({ browser }) => {
  const note = `${NOTE} with Hannah`
  const learner = await parentContext(browser)
  const page = await learner.newPage()
  await signIn(page, 'parenting-learner@hearts.test', 'portal-learner', '/p/parenting/courses')
  await page.goto('/p/parenting/courses')
  await page.getByTestId('course-card').filter({ hasText: 'Welcome' }).first().click()
  await page.getByTestId('start-part').click()
  await expect(page.getByTestId('vimeo-player')).toBeVisible()
  await expect(page.getByTestId('sequence-question')).toContainText('further guidance')
  await page.getByTestId('answer-point').click()
  await page.getByTestId('answer-text').fill(note)
  await page.getByTestId('answer-private').uncheck()
  await page.getByTestId('answer-share').check()
  await page.getByTestId('answer-submit').click()
  await expect(page.getByTestId('popup')).toHaveCount(0)
  await learner.close()

  const teacher = await parentContext(browser)
  const desk = await teacher.newPage()
  await signIn(desk, 'parenting-teacher@hearts.test', 'portal-teacher', '/p/parenting/admin/teach')
  await desk.goto('/p/parenting/admin/teach')
  await expect(desk.getByTestId('teacher-name')).toHaveText('Hannah Price')
  await expect(desk.getByTestId('teacher-shared-answer').filter({ hasText: note })).toBeVisible()
  await shot(desk, 'parent-07-hannah-price')
  await teacher.close()
})

test('ticking both share boxes saves for the teacher and the group', async ({ browser }) => {
  const note = `Both boxes ${Date.now()}`
  const learner = await parentContext(browser)
  const page = await learner.newPage()
  await signIn(page, 'parenting-learner@hearts.test', 'portal-learner', '/p/parenting/courses')
  await page.goto('/p/parenting/courses')
  await page.getByTestId('course-card').filter({ hasText: 'Preparation and resources' }).click()
  await page.getByTestId('start-part').click()
  await expect(page.getByTestId('vimeo-player')).toBeVisible()
  await page.getByTestId('answer-point').click()
  await expect(page.getByTestId('answer-private')).toBeChecked()
  await page.getByTestId('answer-text').fill(note)
  await page.getByTestId('answer-share').check()
  await expect(page.getByTestId('answer-private')).not.toBeChecked()
  await page.getByTestId('answer-share-learners').check()
  await expect(page.getByTestId('answer-share-learners')).toBeChecked()
  await expect(page.getByTestId('answer-private')).not.toBeChecked()
  await page.getByTestId('answer-submit').click()
  await expect(page.getByTestId('popup')).toHaveCount(0)
  await expect(page.getByTestId('notice')).toBeVisible()
  await expect(page.getByTestId('notice')).not.toContainText('Saved privately')
  await expect(page.getByTestId('notice')).toContainText(/shared/)
  await shot(page, 'parent-08-shared-notice')
  await learner.close()

  const teacher = await parentContext(browser)
  const desk = await teacher.newPage()
  await signIn(desk, 'parenting-teacher@hearts.test', 'portal-teacher', '/p/parenting/admin/teach')
  await desk.goto('/p/parenting/admin/teach')
  await expect(desk.getByTestId('teacher-shared-answer').filter({ hasText: note })).toBeVisible()
  await expect(desk.getByTestId('group-shared-answer').filter({ hasText: note })).toBeVisible()
  await shot(desk, 'parent-09-teacher-and-group')
  await teacher.close()

  const viewer = await parentContext(browser)
  const other = await viewer.newPage()
  await signIn(other, 'parenting-admin@hearts.test', 'portal-admin', '/p/parenting/courses')
  await other.goto('/p/parenting/courses')
  await other.getByTestId('course-card').filter({ hasText: 'Preparation and resources' }).click()
  await other.getByTestId('start-part').click()
  await other.getByTestId('answer-point').click()
  await expect(other.getByTestId('swarm-item').filter({ hasText: note })).toBeVisible()
  await shot(other, 'parent-10-group-on-film')
  await viewer.close()
})
