import { expect, test, type Page } from '@playwright/test'
import { seedCode } from '../env'

async function signInTeacher(page: Page) {
  await page.goto('/login')
  await page.getByTestId('login-email').fill('elm-teacher@hearts.test')
  await page.getByTestId('login-password').fill('portal-teacher')
  await page.getByTestId('login-submit').click()
  await page.waitForURL(/\/p\/east-london\/admin\/teach/, { timeout: 30_000 })
}

test('a teacher signing in at /login lands on Teach and can see it as a learner', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await signInTeacher(page)
  await expect(page.getByTestId('admin-teach')).toBeVisible()
  const back = page.locator('.desk').getByTestId('see-as-learner')
  await expect(back).toBeVisible()
  await expect(back).toHaveText('See what a learner sees')
  await expect(page.locator('.side-foot a.nav', { hasText: 'See what a learner sees' })).toBeVisible()
  await back.click()
  await expect(page.getByTestId('home')).toBeVisible()
  expect(new URL(page.url()).pathname).toBe('/p/east-london')
  const desk = page.getByTestId('back-to-desk')
  await expect(desk).toBeVisible()
  await expect(desk).toHaveText('Back to teacher desk')
  await expect(desk).toHaveAttribute('href', '/p/east-london/admin/teach')
  await desk.click()
  await expect(page.getByTestId('admin-teach')).toBeVisible()
  expect(new URL(page.url()).pathname).toBe('/p/east-london/admin/teach')
})

test('on a phone Teach is one column and says See what a learner sees', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await signInTeacher(page)
  await expect(page.getByTestId('desk-narrow')).toBeHidden()
  await expect(page.getByTestId('admin-teach')).toBeVisible()
  const back = page.locator('.desk').getByTestId('see-as-learner')
  await expect(back).toBeVisible()
  await expect(back).toHaveText('See what a learner sees')
  await expect(back).toHaveAttribute('href', '/p/east-london')
  await back.click()
  await expect(page.getByTestId('home')).toBeVisible()
  const desk = page.getByTestId('back-to-desk')
  await expect(desk).toBeVisible()
  const box = await desk.boundingBox()
  expect(box).toBeTruthy()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  await desk.click()
  await expect(page).toHaveURL(/\/p\/east-london\/admin\/teach/)
  await expect(page.getByTestId('desk-narrow')).toBeHidden()
  await expect(page.locator('.desk').getByTestId('see-as-learner')).toBeVisible()
})

test('joining with a teacher code opens Teach, not the learner feed', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  const code = seedCode('elm-teacher')
  const email = `teacher-join-${Date.now()}@hearts.test`
  await page.goto(`/join?code=${encodeURIComponent(code)}`)
  await page.getByTestId('join-name').fill('New Teacher')
  await page.getByTestId('join-email').fill(email)
  await page.getByTestId('join-password').fill('teacher-join')
  await page.getByTestId('join-submit').click()
  await page.waitForURL(/\/p\/east-london\/admin\/teach/, { timeout: 30_000 })
  await expect(page.getByTestId('admin-teach')).toBeVisible()
  expect(page.url()).not.toMatch(/\/feed/)
  await expect(page.locator('.desk').getByTestId('see-as-learner')).toHaveText('See what a learner sees')
})

test('a learner does not see Back to teacher desk', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/login?next=/p/east-london')
  await page.getByTestId('login-email').fill('elm-learner@hearts.test')
  await page.getByTestId('login-password').fill('portal-learner')
  await page.getByTestId('login-submit').click()
  await expect(page.getByTestId('home')).toBeVisible({ timeout: 30_000 })
  await expect(page.getByTestId('back-to-desk')).toHaveCount(0)
})

test('a portal admin gets Back to teacher desk on the learner home and the feed', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/login?next=/p/east-london')
  await page.getByTestId('login-email').fill('elm-admin@hearts.test')
  await page.getByTestId('login-password').fill('portal-admin')
  await page.getByTestId('login-submit').click()
  await expect(page.getByTestId('home')).toBeVisible({ timeout: 30_000 })
  const desk = page.getByTestId('back-to-desk')
  await expect(desk).toHaveAttribute('href', '/p/east-london/admin')
  await page.goto('/p/east-london/feed')
  await expect(page.getByTestId('back-to-desk')).toBeVisible()
  const hit = await page.getByTestId('back-to-desk').evaluate((node) => {
    const box = node.getBoundingClientRect()
    const top = document.elementFromPoint(box.x + box.width / 2, box.y + box.height / 2)
    return top === node || node.contains(top)
  })
  expect(hit).toBe(true)
  await page.getByTestId('back-to-desk').click()
  await expect(page).toHaveURL(/\/p\/east-london\/admin\/?$/)
})
