export function seeHowKeyOwners() {
  const owners = new Map<string, string>()
  for (const page of SEE_HOW_PAGES) {
    for (const key of page.keys) {
      const previous = owners.get(key)
      if (previous && previous !== page.id) throw new Error(`Help key ${key} is on both ${previous} and ${page.id}.`)
      owners.set(key, page.id)
    }
  }
  for (const key of Object.keys(SEE_HOW_SKIPPED)) {
    if (owners.has(key)) throw new Error(`Help key ${key} is both filmed and skipped.`)
  }
  return owners
}
