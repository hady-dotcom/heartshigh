/**
 * One filmed demo per page. Help keys on that page share its video.
 * `npm run see-how:record` walks this list on port 3100.
 */

export type SeeHowRole = 'anon' | 'learner' | 'teacher' | 'portal' | 'master'

export type SeeHowStep = {
  caption: string
  op: 'hold' | 'click' | 'fill' | 'select' | 'check'
  selector?: string
  value?: string
  /** Missing controls are skipped. The caption still shows. */
  optional?: boolean
  /** After the action, wait until this is visible. A miss does not fail the page. */
  waitFor?: string
}

export type SeeHowDiscover =
  | 'course'
  | 'gather-detail'
  | 'gather-reflect'
  | 'gather-door'
  | 'live'
  | 'mission'
  | 'compass-learner'
  | 'ai-step'
  | 'tier'

export type SeeHowPageSpec = {
  id: string
  title: string
  /** Help lookups that play this video. The id is included automatically. */
  keys: string[]
  path: string
  role: SeeHowRole
  viewport: 'phone' | 'desk'
  ready: string
  /** A miss becomes a skip, for screens the seed may not have. */
  soft?: boolean
  discover?: SeeHowDiscover
  steps: SeeHowStep[]
}

