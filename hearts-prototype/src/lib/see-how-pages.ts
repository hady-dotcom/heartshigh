function clip(spec: SeeHowPageSpec): SeeHowPageSpec {
  const keys = [...new Set([spec.id, ...spec.keys])]
  return { ...spec, keys }
}

const hold = (caption: string): SeeHowStep => ({ caption, op: 'hold' })
const click = (caption: string, selector: string, optional = false, waitFor?: string): SeeHowStep => ({ caption, op: 'click', selector, optional, waitFor })
const fill = (caption: string, selector: string, value: string, optional = false): SeeHowStep => ({ caption, op: 'fill', selector, value, optional })
const pick = (caption: string, selector: string, optional = false): SeeHowStep => ({ caption, op: 'select', selector, optional })
const check = (caption: string, selector: string, optional = false): SeeHowStep => ({ caption, op: 'check', selector, optional })

