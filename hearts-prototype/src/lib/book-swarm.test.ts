import assert from 'node:assert/strict'
import test from 'node:test'
import { BOOK_SWARM } from './book-swarm'
import { isHandwrittenAnswer } from './demo-workbook'
import { SWARM_PARENTS } from './swarm-plan'

test('Raising calm, happy children keeps handwritten lines, with no repeated person', () => {
  const names = BOOK_SWARM.flatMap((film) => film.others.map((row) => row.name))
  const bodies = BOOK_SWARM.flatMap((film) => film.others.map((row) => row.body))
  const reserved = new Set<string>(SWARM_PARENTS.map((parent) => parent.name))
  const whole = BOOK_SWARM.filter((film) => film.title.startsWith('The Whole-Brain Child'))
  const danish = BOOK_SWARM.filter((film) => film.title.startsWith('The Danish Way of Parenting'))
  const montessori = BOOK_SWARM.filter((film) => film.title.startsWith('The Montessori Toddler'))
  const extraordinary = BOOK_SWARM.filter((film) => film.title.startsWith('Extraordinary Parenting'))
  const conscious = BOOK_SWARM.filter((film) => film.title.startsWith('The Conscious Parent'))
  const firm = BOOK_SWARM.filter((film) => film.title.startsWith('The Family Firm'))
  const learning = BOOK_SWARM.filter((film) => film.title.startsWith('How Learning Happens'))
  const myths = BOOK_SWARM.filter((film) => film.title.startsWith('Seven Myths About Education'))
  const didau = BOOK_SWARM.filter((film) => film.title.startsWith('What if everything you knew about education was wrong?'))
  const rosenshine = BOOK_SWARM.filter((film) => film.title.startsWith('Rosenshine'))
  const powerful = BOOK_SWARM.filter((film) => film.title.startsWith('Powerful Teaching'))
  const blackBox = BOOK_SWARM.filter((film) => film.title.startsWith('Inside the Black Box'))
  const mindset = BOOK_SWARM.filter((film) => film.title.startsWith('Mindset'))
  const boys = BOOK_SWARM.filter((film) => film.title.startsWith('Boys Don\'t Try?'))
  const celebrity = BOOK_SWARM.filter((film) => film.title.startsWith('Celebrity, Aspiration'))
  const cleverlands = BOOK_SWARM.filter((film) => film.title.startsWith('Cleverlands'))
  const intelligent = BOOK_SWARM.filter((film) => film.title.startsWith('An Intelligent Person'))
  const future = BOOK_SWARM.filter((film) => film.title.startsWith('The Future of Teaching'))
  const turning = BOOK_SWARM.filter((film) => film.title.startsWith('The Turning Point'))
  const sameRace = BOOK_SWARM.filter((film) => film.title.startsWith('The Long-Run Impacts of Same-Race'))
  const trust = BOOK_SWARM.filter((film) => film.title.startsWith('Trust-Based Observations'))
  assert.equal(whole.length, 6)
  assert.equal(danish.length, 7)
  assert.equal(montessori.length, 10)
  assert.equal(extraordinary.length, 5)
  assert.equal(conscious.length, 9)
  assert.equal(firm.length, 6)
  assert.equal(learning.length, 6)
  assert.equal(myths.length, 7)
  assert.equal(didau.length, 5)
  assert.equal(rosenshine.length, 6)
  assert.equal(powerful.length, 10)
  assert.equal(blackBox.length, 3)
  assert.equal(mindset.length, 8)
  assert.equal(boys.length, 10)
  assert.equal(celebrity.length, 11)
  assert.equal(cleverlands.length, 6)
  assert.equal(intelligent.length, 5)
  assert.equal(future.length, 10)
  assert.equal(turning.length, 9)
  assert.equal(sameRace.length, 3)
  assert.equal(trust.length, 7)
  assert.ok(names.length >= 180)
  assert.equal(new Set(names).size, names.length)
  assert.ok(names.every((name) => !reserved.has(name)))
  assert.equal(new Set(bodies.map((body) => body.toLowerCase())).size, bodies.length)
  assert.ok(bodies.every((body) => body.length > 80 && isHandwrittenAnswer(body)))
  assert.ok(BOOK_SWARM.every((film) => film.others.length >= 4 && film.others.length <= 8))
  assert.ok(BOOK_SWARM.every((film) => film.prompt.trim().toLowerCase() !== 'n/a'))
})
